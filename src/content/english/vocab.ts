export const wordId = (en: string): string => `w-${slug(en)}`;
export const wordsOfLevel = (level: EnLevel): EnWord[] => WORDS.filter((w) => w.level === level);
export const wordsOfCategory = (cat: string): EnWord[] => WORDS.filter((w) => w.category === cat);

/** Lowercase surface form → word, for tap-to-translate in readings. Includes simple plurals / -s / -ed forms. */
export const WORD_BY_FORM: Record<string, EnWord> = (() => {
  const m: Record<string, EnWord> = {};
  for (const w of WORDS) {
    const base = w.en.toLowerCase();
    m[base] = w;
    if (!base.includes(' ')) {
      for (const f of [base + 's', base + 'es', base + 'ed', base + 'd', base + 'ing']) m[f] ??= w;
    }
  }
  return m;
})();
