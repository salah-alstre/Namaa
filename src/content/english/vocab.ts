import type { EnLevel, EnWord, PartOfSpeech } from '@/english-engine/types';

/** Compact row: en | ar | pos | pronunciation | example | example (ar) | category */
type Row = string;

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function parse(level: EnLevel, rows: Row[]): EnWord[] {
  return rows.map((r) => {
    const [en, ar, pos, pron, exEn, exAr, category] = r.split('|').map((x) => x.trim());
    return {
      id: `w-${slug(en!)}`,
      en: en!,
      ar: ar!,
      pos: pos as PartOfSpeech,
      pron: pron!,
      exEn: exEn!,
      exAr: exAr!,
      level,
      category: category!,
    };
  });
}

